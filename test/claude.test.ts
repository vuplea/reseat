import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { test } from "node:test";
import {
  GENERATED_MARKER,
  extractTitle,
  isUnextendedImport,
  latestSession,
  projectDirectoryName,
  writeSession,
} from "../src/claude.js";
import type { Turn } from "../src/types.js";
import {
  claudeAssistantRecord,
  claudeUserRecord,
  temporaryStores,
  writeClaudeFixture,
} from "./helpers.js";

test("projectDirectoryName replaces every non-alphanumeric character with a dash", () => {
  if (process.platform === "win32") {
    assert.equal(projectDirectoryName("E:\\Repos\\my-claude"), "E--Repos-my-claude");
    assert.equal(projectDirectoryName("E:\\Repos\\_enc.test_dir"), "E--Repos--enc-test-dir");
    assert.equal(projectDirectoryName("E:\\Repos\\New folder"), "E--Repos-New-folder");
  } else {
    assert.equal(projectDirectoryName("/home/u/repos/app"), "-home-u-repos-app");
    assert.equal(projectDirectoryName("/home/u/repos/a.b_c d"), "-home-u-repos-a-b-c-d");
  }
});

test("extractTitle picks the first real prompt, skipping meta and command noise", async (t) => {
  const stores = await temporaryStores(t);
  const file = await writeClaudeFixture(stores, "proj", [
    { type: "mode", mode: "normal", sessionId: "s" },
    claudeUserRecord("Caveat: the messages below were generated by the user", { isMeta: true }),
    claudeUserRecord("<local-command-stdout>ok</local-command-stdout>"),
    claudeUserRecord("  fix   the\nflaky tests  "),
    claudeAssistantRecord("On it."),
  ]);
  assert.equal(await extractTitle(file), "fix the flaky tests");
});

test("extractTitle returns null when there is no visible prompt", async (t) => {
  const stores = await temporaryStores(t);
  const file = await writeClaudeFixture(stores, "proj", [
    claudeUserRecord("<local-command-stdout>ok</local-command-stdout>"),
  ]);
  assert.equal(await extractTitle(file), null);
});

test("writeSession produces a parent-linked, marker-versioned session", async (t) => {
  const stores = await temporaryStores(t);
  const turns: Turn[] = [
    { role: "user", text: "hello", timestamp: "2026-07-26T10:00:00.000Z" },
    { role: "assistant", text: "hi", timestamp: "2026-07-26T10:00:01.000Z" },
  ];
  const { file, sessionId } = await writeSession(turns, stores.project);
  const records = (await readFile(file, "utf8")).trim().split("\n").map((line) => JSON.parse(line));
  assert.equal(records.length, 2);
  assert.equal(records[0].parentUuid, null);
  assert.equal(records[1].parentUuid, records[0].uuid);
  assert.equal(records[0].sessionId, sessionId);
  assert.equal(path.basename(file), `${sessionId}.jsonl`);
  for (const record of records) assert.equal(record.version, GENERATED_MARKER);
  assert.equal(records[0].message.content[0].text, "hello");
  assert.equal(records[1].type, "assistant");
});

test("isUnextendedImport: true for freshly written sessions, false once extended or for native sessions", async (t) => {
  const stores = await temporaryStores(t);
  const { file } = await writeSession([{ role: "user", text: "hi" }], stores.project);
  assert.equal(await isUnextendedImport(file), true);

  const native = await writeClaudeFixture(stores, "native", [claudeUserRecord("hello")]);
  assert.equal(await isUnextendedImport(native), false);

  const extendedRecords = (await readFile(file, "utf8")).trim().split("\n").map((line) => JSON.parse(line));
  extendedRecords.push(claudeUserRecord("continued in claude"));
  const extended = await writeClaudeFixture(stores, "extended", extendedRecords);
  assert.equal(await isUnextendedImport(extended), false);
});

test("latestSession returns the newest non-agent session file", async (t) => {
  const stores = await temporaryStores(t);
  const name = projectDirectoryName(stores.project);
  await writeClaudeFixture(stores, name, [claudeUserRecord("old")], { mtime: new Date("2026-07-26T09:00:00Z") });
  const newest = await writeClaudeFixture(stores, name, [claudeUserRecord("new")], { mtime: new Date("2026-07-26T11:00:00Z") });
  await writeClaudeFixture(stores, name, [claudeUserRecord("agent")], {
    name: "agent-123.jsonl",
    mtime: new Date("2026-07-26T12:00:00Z"),
  });
  assert.equal(await latestSession(stores.project), newest);
});
